# Print numbers from 1 to 10
print("Numbers from 1 to 10:")
count = 1

while count <= 10:
    print(count)
    count += 1

# Print even numbers from 2 to 20
print("\nEven Numbers:")
num = 2

while num <= 20:
    print(num)
    num += 2

# Countdown Timer
print("\nCountdown:")

timer = 5

while timer > 0:
    print(timer)
    timer -= 1

print("🚀 Time's Up!")
